END $$;
SET timezone TO 'Asia/Kolkata';

-- Re-runnable: drop children before parents.
DROP TABLE IF EXISTS inspection         CASCADE;
DROP TABLE IF EXISTS customs_filing     CASCADE;
DROP TABLE IF EXISTS shipment_container CASCADE;
DROP TABLE IF EXISTS container          CASCADE;
DROP TABLE IF EXISTS shipment           CASCADE;
DROP TABLE IF EXISTS shipping_manifest  CASCADE;
DROP TABLE IF EXISTS port_call          CASCADE;
DROP TABLE IF EXISTS berth              CASCADE;
DROP TABLE IF EXISTS company            CASCADE;
DROP TABLE IF EXISTS vessel             CASCADE;
DROP DOMAIN   IF EXISTS cargo_category;
DROP FUNCTION IF EXISTS is_valid_imo(TEXT);

-- ---------------------------------------------------------------------
-- Shared domain: vessel_type and berth.cargo_type must use the same
-- vocabulary, otherwise allocate_berth() cannot match a ship to a berth.
-- ---------------------------------------------------------------------
CREATE DOMAIN cargo_category AS VARCHAR(20)
    CHECK (VALUE IN ('Container', 'Bulk', 'Tanker', 'General Cargo', 'RoRo'));

-- ---------------------------------------------------------------------
-- IMO number check digit: digits 1-6 are weighted 7,6,5,4,3,2; the last
-- digit of the weighted sum must equal digit 7.  e.g. 9321483:
-- 9*7 + 3*6 + 2*5 + 1*4 + 4*3 + 8*2 = 123 -> 3.
-- IMMUTABLE so it is allowed inside a CHECK constraint.
-- ---------------------------------------------------------------------
CREATE FUNCTION is_valid_imo(imo TEXT) RETURNS BOOLEAN
LANGUAGE sql IMMUTABLE AS $$
    SELECT imo ~ '^[0-9]{7}$'
       AND ( substr(imo,1,1)::int * 7 + substr(imo,2,1)::int * 6
           + substr(imo,3,1)::int * 5 + substr(imo,4,1)::int * 4
           + substr(imo,5,1)::int * 3 + substr(imo,6,1)::int * 2 ) % 10
           = substr(imo,7,1)::int;
$$;

-- 1. VESSEL -----------------------------------------------------------
CREATE TABLE vessel (
    imo_number   CHAR(7)        PRIMARY KEY
                                CHECK (is_valid_imo(imo_number)),
    mmsi         CHAR(9)        NOT NULL UNIQUE          -- join key to MongoDB ship_location
                                CHECK (mmsi ~ '^[0-9]{9}$'),
    vessel_name  VARCHAR(100)   NOT NULL,
    flag         VARCHAR(50)    NOT NULL,
    vessel_type  cargo_category NOT NULL,
    loa          NUMERIC(6,2)   NOT NULL CHECK (loa > 0),     -- length overall, metres
    draft        NUMERIC(5,2)   NOT NULL CHECK (draft > 0)    -- metres
);

-- 2. COMPANY ----------------------------------------------------------
CREATE TABLE company (
    company_id    INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name  VARCHAR(150)  NOT NULL,
    iec_code      CHAR(10)      UNIQUE                   -- Importer-Exporter Code; agents may not have one
                                CHECK (iec_code ~ '^[A-Z0-9]{10}$'),
    company_type  VARCHAR(10)   NOT NULL
                                CHECK (company_type IN ('agent', 'shipper', 'consignee'))
);

-- 3. BERTH ------------------------------------------------------------
CREATE TABLE berth (
    berth_number  VARCHAR(10)    PRIMARY KEY,
    max_loa       NUMERIC(6,2)   NOT NULL CHECK (max_loa > 0),
    max_draft     NUMERIC(5,2)   NOT NULL CHECK (max_draft > 0),
    cargo_type    cargo_category NOT NULL
);

-- 4. PORT_CALL --------------------------------------------------------
-- One berth per visit, so the berth is a nullable FK here (no separate
-- allocation table).  waiting_time is derived in v_waiting_time, never stored.
CREATE TABLE port_call (
    call_id        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imo_number     CHAR(7)      NOT NULL REFERENCES vessel(imo_number),
    agent_id       INTEGER      NOT NULL REFERENCES company(company_id),
    berth_number   VARCHAR(10)  REFERENCES berth(berth_number),   -- NULL until allocated
    berth_start    TIMESTAMPTZ,
    berth_end      TIMESTAMPTZ,
    eta            TIMESTAMPTZ  NOT NULL,      -- agent-declared
    predicted_eta  TIMESTAMPTZ,                -- written back by the ML model
    ata            TIMESTAMPTZ,                -- actual arrival at anchorage (geofence)
    atd            TIMESTAMPTZ,                -- actual departure
    call_status    VARCHAR(10)  NOT NULL DEFAULT 'Expected'
                   CHECK (call_status IN ('Expected', 'Waiting', 'Berthed', 'Departed')),

    -- a berth window only makes sense if a berth is assigned
    CONSTRAINT chk_window_needs_berth
        CHECK (berth_number IS NOT NULL OR (berth_start IS NULL AND berth_end IS NULL)),
    CONSTRAINT chk_berth_window
        CHECK (berth_end IS NULL OR (berth_start IS NOT NULL AND berth_end > berth_start)),
    CONSTRAINT chk_arrival_before_berth
        CHECK (ata IS NULL OR berth_start IS NULL OR berth_start >= ata),
    CONSTRAINT chk_departure_after_arrival
        CHECK (atd IS NULL OR ata IS NULL OR atd >= ata),
    CONSTRAINT chk_departure_after_unberth
        CHECK (atd IS NULL OR berth_end IS NULL OR atd >= berth_end)
);

-- 5. SHIPPING_MANIFEST ------------------------------------------------
-- "At most 2 manifests per call, one import + one export" is enforced
-- declaratively by UNIQUE (call_id, manifest_type): with only two allowed
-- types, a third manifest would always duplicate one of them.
CREATE TABLE shipping_manifest (
    manifest_no    VARCHAR(20)  PRIMARY KEY,
    call_id        INTEGER      NOT NULL REFERENCES port_call(call_id),
    manifest_type  CHAR(3)      NOT NULL CHECK (manifest_type IN ('IGM', 'EGM')),
    filing_date    DATE         NOT NULL,
    CONSTRAINT uq_one_manifest_per_type UNIQUE (call_id, manifest_type)
);

-- 6. SHIPMENT (one Bill of Lading) -------------------------------------
CREATE TABLE shipment (
    shipment_no        VARCHAR(20)    PRIMARY KEY,               -- B/L number
    manifest_no        VARCHAR(20)    NOT NULL REFERENCES shipping_manifest(manifest_no),
    shipper_id         INTEGER        NOT NULL REFERENCES company(company_id),
    consignee_id       INTEGER        NOT NULL REFERENCES company(company_id),
    cargo_description  TEXT           NOT NULL,
    origin_port        CHAR(5)        NOT NULL                   -- UN/LOCODE, e.g. CNSHA
                                      CHECK (origin_port ~ '^[A-Z]{2}[A-Z2-9]{3}$'),
    hs_code            VARCHAR(8)     NOT NULL                   -- 6-digit HS or 8-digit ITC-HS
                                      CHECK (hs_code ~ '^[0-9]{6}([0-9]{2})?$'),
    cargo_quantity     INTEGER        NOT NULL CHECK (cargo_quantity > 0),
    gross_weight       NUMERIC(12,2)  NOT NULL CHECK (gross_weight > 0),   -- kg
    CONSTRAINT chk_shipper_not_consignee CHECK (shipper_id <> consignee_id)
);

-- 7. CONTAINER --------------------------------------------------------
-- size is determined by the first character of the ISO 6346 type code
-- (2 = 20 ft, 4 = 40 ft, L = 45 ft).  The CHECK keeps the two consistent.
CREATE TABLE container (
    container_no  CHAR(11)  PRIMARY KEY
                            CHECK (container_no ~ '^[A-Z]{4}[0-9]{7}$'),
    iso_type      CHAR(4)   NOT NULL CHECK (iso_type ~ '^[24L][0-9A-Z]{3}$'),
    size          SMALLINT  NOT NULL CHECK (size IN (20, 40, 45)),
    CONSTRAINT chk_size_matches_iso CHECK (
           (size = 20 AND iso_type LIKE '2%')
        OR (size = 40 AND iso_type LIKE '4%')
        OR (size = 45 AND iso_type LIKE 'L%'))
);

-- 8. SHIPMENT_CONTAINER (M:N, "COVERS") --------------------------------
CREATE TABLE shipment_container (
    shipment_no       VARCHAR(20)  REFERENCES shipment(shipment_no) ON DELETE CASCADE,
    container_no      CHAR(11)     REFERENCES container(container_no),
    seal_no           VARCHAR(15),
    container_status  VARCHAR(12)  NOT NULL DEFAULT 'Loaded'
                      CHECK (container_status IN ('Loaded', 'Discharged', 'Held', 'Released')),
    PRIMARY KEY (shipment_no, container_no)
);

-- 9. CUSTOMS_FILING (1:1 with SHIPMENT via UNIQUE FK) -------------------
CREATE TABLE customs_filing (
    filing_no       VARCHAR(20)    PRIMARY KEY,
    shipment_no     VARCHAR(20)    NOT NULL UNIQUE REFERENCES shipment(shipment_no),
    filing_type     VARCHAR(15)    NOT NULL
                    CHECK (filing_type IN ('Bill of Entry', 'Shipping Bill')),
    filing_date     DATE           NOT NULL,
    declared_value  NUMERIC(14,2)  NOT NULL CHECK (declared_value >= 0),   -- INR
    duty_amount     NUMERIC(14,2)  CHECK (duty_amount >= 0),               -- NULL until assessed
    filing_status   VARCHAR(15)    NOT NULL DEFAULT 'Filed'
                    CHECK (filing_status IN ('Filed', 'Under Review', 'Held', 'Cleared')),
    risk_score      NUMERIC(4,3)   CHECK (risk_score BETWEEN 0 AND 1)      -- NULL until scored
);

-- 10. INSPECTION (weak entity, owner = CUSTOMS_FILING) ------------------
-- Identified by (owner key, partial key).  ON DELETE CASCADE because an
-- inspection cannot exist without its filing.
CREATE TABLE inspection (
    filing_no        VARCHAR(20)  REFERENCES customs_filing(filing_no) ON DELETE CASCADE,
    inspection_no    SMALLINT     CHECK (inspection_no > 0),   -- partial key: 1, 2, ... per filing
    inspection_date  DATE         NOT NULL,
    officer_name     VARCHAR(100) NOT NULL,
    result           VARCHAR(12)  NOT NULL DEFAULT 'Pending'
                     CHECK (result IN ('Pending', 'Clear', 'Discrepancy')),
    remarks          TEXT,
    PRIMARY KEY (filing_no, inspection_no)
);

-- ---------------------------------------------------------------------
-- Indexes.  PostgreSQL indexes PKs and UNIQUE columns automatically but
-- NOT foreign keys, so the hot lookup paths are added here.
-- ---------------------------------------------------------------------
CREATE INDEX idx_port_call_berth_time   ON port_call (berth_number, berth_start);  -- overlap trigger, allocate_berth
CREATE INDEX idx_shipment_hs_code       ON shipment (hs_code);                     -- risk model, HS lookups
CREATE INDEX idx_customs_filing_status  ON customs_filing (filing_status);         -- v_pending_customs
