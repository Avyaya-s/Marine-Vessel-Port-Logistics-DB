-- Run order:  schema.sql -> triggers.sql -> sample_data.sql
-- Tables are created parents-first so every FK target already exists.
-- SHIP_LOCATION and WEATHER_LOG live in MongoDB (see mongo_setup.js).
-- =====================================================================

